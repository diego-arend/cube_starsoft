import fs from "fs";
import path from "path";
import { loadConfig } from "../../load";
import { EnvSchema, isSafeForFrontend, EnvAnnotations } from "../../schema";

export interface GenerateOptions {
  outputPath: string;
  override?: boolean;
  dryRun?: boolean;
}

export function generateFrontendEnv({
  outputPath,
  override = true,
  dryRun = false,
}: GenerateOptions) {
  console.log("🔍 Validating environment variables from config.yaml...");

  // 1. Load config (merging with process.env to allow overrides from shell if needed)
  const loaded = loadConfig();
  const merged = { ...loaded, ...process.env };

  // 2. Validate with Schema - This satisfies the requirement:
  // "If any environment variable is missing or incorrectly formatted, even from the frontend, the turborepo build breaks."
  const result = EnvSchema.safeParse(merged);

  if (!result.success) {
    console.error("❌ Invalid configuration detected:");
    console.error(JSON.stringify(result.error.format(), null, 2));
    process.exit(1);
  }

  const validatedEnv = result.data as Record<string, unknown>;

  // 3. Extract frontend-specific variables
  // Only keys that are *explicitly annotated* as safe for the frontend will be
  // exported. This avoids accidental leakage of secrets.
  const frontendEnv: Record<string, string> = {};

  // Collect annotated keys that are present in the validated env
  for (const [key, value] of Object.entries(validatedEnv)) {
    if (value === undefined) continue;
    if (isSafeForFrontend(key)) {
      frontendEnv[key] = String(value);
    }
  }

  // Warn about annotations that don't have a corresponding value (helpful during schema edits)
  const annotatedKeys = Object.keys(EnvAnnotations).filter(
    (k) => !!EnvAnnotations[k]?.safeForFrontend
  );
  for (const k of annotatedKeys) {
    if (validatedEnv[k] === undefined) {
      console.warn(
        `⚠️  Annotated frontend key ${k} is not present in validated config; ensure it's defined in config.yaml if you intended to export it.`
      );
    }
  }

  // IMPORTANT: No automatic mapping (e.g., FRONTEND_AUTH_SECRET -> AUTH_SECRET) is performed.
  // If you need AUTH_SECRET in the frontend, annotate it explicitly in `EnvAnnotations`.

  // 4. Generate .env file content
  const header = `# GENERATED BY @turborepo/config - DO NOT EDIT MANUALLY\n# Generated at: ${new Date().toISOString()}\n\n`;
  const body = Object.entries(frontendEnv)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([key, value]) => `${key}="${value.replace(/"/g, '\\"')}"`)
    .join("\n");

  const content = header + body + "\n";

  if (dryRun) {
    console.log("✨ [Dry Run] Generated content:");
    console.log(content);
    return;
  }

  // 5. Write to file
  const fullPath = path.resolve(outputPath);
  const dir = path.dirname(fullPath);

  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }

  if (fs.existsSync(fullPath) && !override) {
    console.log(`⚠️  File ${fullPath} already exists. Skipping.`);
    return;
  }

  fs.writeFileSync(fullPath, content, "utf8");
  console.log(`✅ Frontend .env generated successfully at: ${fullPath}`);
}
