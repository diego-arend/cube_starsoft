import fs from "fs";
import path from "path";
import { loadConfig } from "../../load";
import { EnvSchema } from "../../schema";
import { ServiceExclusions } from "./constants";

export interface GenerateOptions {
  outputPath: string;
  override?: boolean;
  dryRun?: boolean;
  appName: string;
  /**
   * The type of application (BACKEND, WORKER, etc.) to apply
   * standard exclusions defined in constants.ts.
   */
  serviceType?: keyof typeof ServiceExclusions;
  /**
   * Additional manual prefix exclusions.
   */
  excludePrefixes?: string[];
  filter?: (key: string) => boolean;
}

/**
 * Generates a .env file for a Node.js application (Backend, Worker, etc.)
 * by validating config.yaml against EnvSchema.
 */
export function generateNodeEnv({
  outputPath,
  override = true,
  dryRun = false,
  appName,
  serviceType,
  excludePrefixes = [],
  filter,
}: GenerateOptions) {
  console.log(
    `🔍 Validating environment variables for ${appName} from config.yaml...`
  );

  // 1. Load config (merging with process.env to allow overrides from shell if needed)
  const loaded = loadConfig();
  const merged = { ...loaded, ...process.env };

  // 2. Validate with Schema
  const result = EnvSchema.safeParse(merged);

  if (!result.success) {
    console.error(`❌ Invalid configuration detected for ${appName}:`);
    console.error(JSON.stringify(result.error.format(), null, 2));
    process.exit(1);
  }

  const validatedEnv = result.data as Record<string, unknown>;

  // 3. Resolve all exclusions (standard from serviceType + manual)
  const allExclusions = [
    ...(serviceType ? ServiceExclusions[serviceType] : []),
    ...excludePrefixes,
  ];

  // 4. Generate .env file content (filtered for Node apps)
  const header = `# GENERATED BY @turborepo/config for ${appName} - DO NOT EDIT MANUALLY\n# Generated at: ${new Date().toISOString()}\n\n`;
  const body = Object.entries(validatedEnv)
    .sort(([a], [b]) => a.localeCompare(b))
    .filter(([key]) => {
      // If a custom filter is provided, use it
      if (filter) {
        return filter(key);
      }
      // Otherwise fallback to prefix exclusion
      return !allExclusions.some((prefix) => key.startsWith(prefix));
    })
    .map(([key, value]) => {
      if (value === undefined) return null;
      let finalKey = key;
      if (appName === "Backend" && key === "BACKEND_PORT") {
        finalKey = "PORT";
      } else if (appName === "Worker" && key === "WORKER_PORT") {
        finalKey = "PORT";
      }
      return `${finalKey}="${String(value).replace(/"/g, '\\"')}"`;
    })
    .filter(Boolean)
    .join("\n");

  const content = header + body + "\n";

  if (dryRun) {
    console.log(`✨ [Dry Run] Generated content for ${appName}:`);
    console.log(content);
    return;
  }

  // 4. Write to file
  const fullPath = path.resolve(outputPath);
  const dir = path.dirname(fullPath);

  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }

  if (fs.existsSync(fullPath) && !override) {
    console.log(`⚠️  File ${fullPath} already exists. Skipping.`);
    return;
  }

  fs.writeFileSync(fullPath, content, "utf8");
  console.log(`✅ ${appName} .env generated successfully at: ${fullPath}`);
}
